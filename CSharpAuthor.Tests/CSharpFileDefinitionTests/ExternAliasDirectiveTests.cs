using Xunit;

namespace CSharpAuthor.Tests.CSharpFileDefinitionTests;

/// <summary>
/// <see cref="CSharpFileDefinition.AddExternAlias"/>, and the <c>extern alias</c> directive a file
/// writes for a type marked with <see cref="ITypeDefinitionExtensions.WithExternAlias"/>.
/// </summary>
/// <remarks>
/// The files are compiled against <see cref="AliasedVendor"/>, referenced as <c>V1</c>, and
/// <see cref="GlobalVendor"/>, which both declare <c>Vendor.Widgets.Widget</c>. Each file reads a
/// member only the aliased assembly's type has, so a name that lost its alias binds to the global
/// assembly and the read is CS1061. A missing directive is CS0432, a duplicated one CS1537, and one
/// written after a using or an attribute CS0439.
/// </remarks>
public class ExternAliasDirectiveTests
{
    private const string AliasedSource = @"
namespace Vendor.Widgets
{
    public class Widget
    {
        public int FromV1;

        public class Part { public int PartFromV1; }
    }

    public static class WidgetMath
    {
        public static int Twice(int value) => value * 2;
    }

    public sealed class MarkAttribute : System.Attribute { }
}
";

    private const string GlobalSource = @"
namespace Vendor.Widgets
{
    public class Widget
    {
        public int FromV2;

        public class Part { }
    }
}

namespace V1.Tools
{
    public class Helper { public int FromHelper; }
}

namespace Tools
{
    public class V1 { public int FromToolsV1; }
}
";

    private static readonly MetadataReference AliasedVendor = RoslynAssert.Reference("VendorV1", AliasedSource, "V1");

    private static readonly MetadataReference GlobalVendor = RoslynAssert.Reference("VendorV2", GlobalSource);

    private static readonly ITypeDefinition V1Widget =
        TypeDefinition.Get("Vendor.Widgets", "Widget").WithExternAlias("V1");

    private static readonly ITypeDefinition V1WidgetMath =
        TypeDefinition.Get(TypeDefinitionEnum.ClassDefinition, "Vendor.Widgets", "WidgetMath").WithExternAlias("V1");

    private static readonly ITypeDefinition V1Mark =
        TypeDefinition.Get(TypeDefinitionEnum.ClassDefinition, "Vendor.Widgets", "MarkAttribute").WithExternAlias("V1");

    public static IEnumerable<object[]> Modes() => new[]
    {
        new object[] { TypeOutputMode.ShortName },
        new object[] { TypeOutputMode.FullName },
        new object[] { TypeOutputMode.Global },
    };

    private static string Render(CSharpFileDefinition file, TypeOutputMode mode) =>
        Emit.File(file, new OutputContextOptions { TypeOutputMode = mode });

    private static string[] Lines(string code) => code.Replace("\r\n", "\n").Split('\n');

    private static int FirstLine(string[] lines, string prefix) =>
        Array.FindIndex(lines, line => line.StartsWith(prefix, StringComparison.Ordinal));

    private static int Count(string code, string line) =>
        Lines(code).Count(l => string.Equals(l, line, StringComparison.Ordinal));

    /// <summary>
    /// Everything C# allows before a namespace: the header, the directive, a file-level using, a
    /// caller alias, a <c>using static</c> and an assembly attribute, each naming the aliased
    /// assembly where it can.
    /// </summary>
    [Theory]
    [MemberData(nameof(Modes))]
    public void TheDirectiveIsWrittenAfterTheHeaderAndBeforeEverythingElse(TypeOutputMode mode)
    {
        var file = new CSharpFileDefinition("Sample");
        file.AddAutoGeneratedHeader();
        file.Comment = "Widgets.";
        file.AddExternAlias("V1");
        file.AddUsingNamespace("System.Text");
        file.AddUsingAlias("VW", V1Widget);
        file.AddUsingStatic(V1WidgetMath);
        file.AddComponent(new AttributeDefinition(V1Mark) { Target = "assembly" });

        var holder = file.AddClass("Holder");
        holder.AddProperty(V1Widget, "Value");
        holder.AddProperty(typeof(StringBuilder), "Buffer");
        holder.AddMethod("Check").AddCode("_ = Value.FromV1;\nVW other = new VW();\n_ = other.FromV1;\n_ = Twice(2);");

        var output = Render(file, mode);
        var lines = Lines(output);

        var directive = Array.IndexOf(lines, "extern alias V1;");
        var marker = Array.IndexOf(lines, "// <auto-generated/>");
        var comment = FirstLine(lines, "///");
        var firstUsing = FirstLine(lines, "using ");
        var attribute = FirstLine(lines, "[assembly:");

        Assert.True(marker >= 0 && marker < directive, output);
        Assert.True(comment >= 0 && comment < directive, output);
        Assert.True(directive < firstUsing, output);
        Assert.True(firstUsing < attribute, output);
        Assert.Equal(1, Count(output, "extern alias V1;"));
        Assert.Contains("using VW = V1::Vendor.Widgets.Widget;", output);
        Assert.Contains("using static V1::Vendor.Widgets.WidgetMath;", output);
        Assert.Contains("[assembly: V1::Vendor.Widgets.Mark]", output);

        RoslynAssert.CompilesWithReferences(output, AliasedVendor, GlobalVendor);
    }

    /// <summary>
    /// ShortName records the file and serializes it in Output; Global streams it as it is written.
    /// The downlevel notes and the directives are put in after the header on both paths.
    /// </summary>
    [Theory]
    [InlineData(TypeOutputMode.ShortName)]
    [InlineData(TypeOutputMode.Global)]
    public void TheDirectiveIsWrittenAfterTheDownlevelNotes(TypeOutputMode mode)
    {
        var profile = EmitProfile.Conservative.With(p =>
        {
            p.DownlevelComments = DownlevelCommentPlacement.FileHeader;
            p.TypeMode = mode;
        });

        var file = new CSharpFileDefinition("Gen");
        file.AddAutoGeneratedHeader();
        file.AddExternAlias("V1");

        var widget = file.AddClass("Holder");
        var name = widget.AddProperty(typeof(string), "Name");
        name.Set!.IsInit = true;
        widget.AddProperty(typeof(StringBuilder), "Buffer");
        widget.AddProperty(V1Widget, "Value");

        var output = ProfileEmitter.Emit(file, profile).Code;
        var lines = Lines(output);

        var directive = Array.IndexOf(lines, "extern alias V1;");

        Assert.Equal("// <auto-generated/>", lines[0]);
        Assert.StartsWith("// DOWNLEVEL:", lines[1]);
        var firstUsing = FirstLine(lines, "using ");

        Assert.True(directive > 1, output);
        Assert.True(firstUsing < 0 || directive < firstUsing, output);
        Assert.Equal(1, Count(output, "extern alias V1;"));

        RoslynAssert.CompilesWithReferences(output, AliasedVendor, GlobalVendor);
    }

    public static IEnumerable<object[]> MarkedTypePlaces()
    {
        var places = new[]
        {
            "property", "type argument", "nested type", "attribute", "code argument", "using alias target",
            "using static target", "namespace alias target", "assembly attribute",
        };

        foreach (var place in places)
        {
            foreach (var mode in new[] { TypeOutputMode.ShortName, TypeOutputMode.FullName, TypeOutputMode.Global })
            {
                yield return new object[] { place, mode };
            }
        }
    }

    /// <summary>
    /// No <see cref="CSharpFileDefinition.AddExternAlias"/> call: the marked type written in the
    /// file brings its directive with it.
    /// </summary>
    [Theory]
    [MemberData(nameof(MarkedTypePlaces))]
    public void AMarkedTypeAddsItsDirective(string place, TypeOutputMode mode)
    {
        var file = new CSharpFileDefinition("Sample");
        var holder = file.AddClass("Holder");
        var check = holder.AddMethod("Check");

        switch (place)
        {
            case "property":
                holder.AddProperty(V1Widget, "Value");
                check.AddCode("_ = Value.FromV1;");
                break;
            case "type argument":
                holder.AddProperty(
                    new GenericTypeDefinition(TypeDefinitionEnum.ClassDefinition, "System.Collections.Generic", "List", new[] { V1Widget }),
                    "Values");
                check.AddCode("_ = Values[0].FromV1;");
                break;
            case "nested type":
                holder.AddProperty(TypeDefinition.GetNested(V1Widget, "Part"), "Value");
                check.AddCode("_ = Value.PartFromV1;");
                break;
            case "attribute":
                holder.AddAttribute(V1Mark);
                break;
            case "code argument":
                check.AddCode("var value = new {arg1}();\n_ = value.FromV1;", V1Widget);
                break;
            case "using alias target":
                file.AddUsingAlias("VW", V1Widget);
                check.AddCode("var value = new VW();\n_ = value.FromV1;");
                break;
            case "using static target":
                file.AddUsingStatic(V1WidgetMath);
                check.AddCode("_ = Twice(2);");
                break;
            case "namespace alias target":
                var inner = new NamespaceDefinition("Inner");
                inner.AddUsingAlias("VW", V1Widget);
                inner.AddClass("InnerHolder").AddMethod("Check").AddCode("var value = new VW();\n_ = value.FromV1;");
                file.AddComponent(inner);
                break;
            case "assembly attribute":
                file.AddComponent(new AttributeDefinition(V1Mark) { Target = "assembly" });
                break;
        }

        var output = Render(file, mode);
        var lines = Lines(output);

        Assert.Equal(1, Count(output, "extern alias V1;"));
        Assert.Equal(0, Array.IndexOf(lines, "extern alias V1;"));

        RoslynAssert.CompilesWithReferences(output, AliasedVendor, GlobalVendor);
    }

    [Fact]
    public void AFileWithNoMarkedTypeWritesNoDirective()
    {
        var file = new CSharpFileDefinition("Sample");
        file.AddClass("Holder").AddProperty(TypeDefinition.Get("Vendor.Widgets", "Widget"), "Value");

        Assert.DoesNotContain("extern alias", Render(file, TypeOutputMode.ShortName));
    }

    [Theory]
    [MemberData(nameof(Modes))]
    public void TheSameNameIsWrittenOnce(TypeOutputMode mode)
    {
        var file = new CSharpFileDefinition("Sample");
        file.AddExternAlias("V1");
        file.AddExternAlias("@V1");
        file.AddExternAlias("V1");

        var holder = file.AddClass("Holder");
        holder.AddProperty(V1Widget, "Value");
        holder.AddProperty(TypeDefinition.GetNested(V1Widget, "Part"), "Piece");
        holder.AddMethod("Check").AddCode("_ = Value.FromV1;\n_ = Piece.PartFromV1;");

        var output = Render(file, mode);

        Assert.Equal(1, Count(output, "extern alias V1;"));

        RoslynAssert.CompilesWithReferences(output, AliasedVendor, GlobalVendor);
    }

    [Fact]
    public void DirectivesAreWrittenInTheOrderTheyWereAddedOrMet()
    {
        var file = new CSharpFileDefinition("Sample");
        file.AddExternAlias("V2");

        var holder = file.AddClass("Holder");
        holder.AddProperty(TypeDefinition.Get("Vendor.Widgets", "Widget").WithExternAlias("V3"), "Third");
        holder.AddProperty(V1Widget, "First");

        var output = Render(file, TypeOutputMode.ShortName);

        Assert.StartsWith("extern alias V2;\nextern alias V3;\nextern alias V1;\n", output.Replace("\r\n", "\n"));
    }

    [Theory]
    [InlineData("event")]
    [InlineData("@event")]
    public void AKeywordNameIsWrittenWithAnAt(string name)
    {
        var file = new CSharpFileDefinition("Sample");
        file.AddExternAlias(name);

        var holder = file.AddClass("Holder");
        holder.AddProperty(TypeDefinition.Get("Vendor.Widgets", "Widget").WithExternAlias("event"), "Value");
        holder.AddMethod("Check").AddCode("_ = Value.FromV1;");

        var output = Render(file, TypeOutputMode.ShortName);

        Assert.Equal(1, Count(output, "extern alias @event;"));

        RoslynAssert.CompilesWithReferences(
            output, RoslynAssert.Reference("VendorEvent", AliasedSource, "event"), GlobalVendor);
    }

    [Theory]
    [InlineData("global")]
    [InlineData("@global")]
    [InlineData("")]
    [InlineData("Two Words")]
    [InlineData("V1::")]
    [InlineData("Vendor.V1")]
    [InlineData("1V")]
    public void ANameCSharpDoesNotAllowIsRefused(string name)
    {
        var file = new CSharpFileDefinition("Sample");

        Assert.Throws<ArgumentException>(() => file.AddExternAlias(name));
    }

    [Fact]
    public void ANullNameIsRefused()
    {
        var file = new CSharpFileDefinition("Sample");

        Assert.Throws<ArgumentException>(() => file.AddExternAlias(null!));
    }

    /// <summary>
    /// <c>V1.Tools.Helper</c> and <c>Tools.V1</c> are unmarked types in the global assembly. With
    /// <c>extern alias V1;</c> in force, a name starting <c>V1</c> is ambiguous between the alias and
    /// the global namespace or type (CS0576, CS0104), so both are written <c>global::</c>-qualified
    /// where they would otherwise start with <c>V1</c>.
    /// </summary>
    [Theory]
    [MemberData(nameof(Modes))]
    public void ATypeNamedLikeTheAliasIsNotCapturedByIt(TypeOutputMode mode)
    {
        var file = new CSharpFileDefinition("Sample");
        file.AddExternAlias("V1");

        var holder = file.AddClass("Holder");
        holder.AddProperty(TypeDefinition.Get("V1.Tools", "Helper"), "Helper");
        holder.AddProperty(TypeDefinition.Get("Tools", "V1"), "Named");
        holder.AddProperty(V1Widget, "Value");
        holder.AddMethod("Check").AddCode("_ = Helper.FromHelper;\n_ = Named.FromToolsV1;\n_ = Value.FromV1;");

        var output = Render(file, mode);

        RoslynAssert.CompilesWithReferences(output, AliasedVendor, GlobalVendor);
    }

    /// <summary>
    /// The same, with the directive brought by the marked type rather than added by the caller.
    /// The marked type is written first, so its alias is known before the others are written.
    /// </summary>
    [Theory]
    [MemberData(nameof(Modes))]
    public void ATypeNamedLikeAnAliasMetEarlierIsNotCapturedByIt(TypeOutputMode mode)
    {
        var file = new CSharpFileDefinition("Sample");

        var holder = file.AddClass("Holder");
        holder.AddProperty(V1Widget, "Value");
        holder.AddProperty(TypeDefinition.Get("V1.Tools", "Helper"), "Helper");
        holder.AddProperty(TypeDefinition.Get("Tools", "V1"), "Named");
        holder.AddMethod("Check").AddCode("_ = Helper.FromHelper;\n_ = Named.FromToolsV1;\n_ = Value.FromV1;");

        var output = Render(file, mode);

        Assert.Equal(1, Count(output, "extern alias V1;"));

        RoslynAssert.CompilesWithReferences(output, AliasedVendor, GlobalVendor);
    }

    /// <summary>
    /// An <see cref="IOutputContext"/> that is not an <see cref="OutputContext"/> is handed the
    /// directives as text, in the same place.
    /// </summary>
    [Fact]
    public void AnotherContextIsHandedTheDirectiveFirst()
    {
        var file = new CSharpFileDefinition("Sample");
        file.AddExternAlias("event");
        file.AddUsingStatic(TypeDefinition.Get(typeof(Math)));

        var context = new RecordingContext();

        file.WriteOutput(context);

        var text = context.Text.ToString();

        Assert.StartsWith("extern alias @event;", text);
        Assert.True(text.IndexOf("extern alias", StringComparison.Ordinal) <
                    text.IndexOf("using static", StringComparison.Ordinal), text);
    }

    private sealed class RecordingContext : IOutputContext
    {
        public StringBuilder Text { get; } = new();

        public string SingleIndent => "";

        public string IndentString => "";

        public OutputContextOptions Options { get; } = new();

        public char? LastCharacter => Text.Length == 0 ? null : Text[Text.Length - 1];

        public void IncrementIndent() { }

        public void DecrementIndent() { }

        public void Write(string text) => Text.Append(text);

        public void Write(ITypeDefinition typeDefinition) => typeDefinition.WriteTypeName(Text, TypeOutputMode.Global);

        public void WriteLine() => Text.Append('\n');

        public void WriteLine(string text) => Text.Append(text).Append('\n');

        public void WriteSpace() => Text.Append(' ');

        public void WriteIndent(string text = "") => Text.Append(text);

        public void WriteIndentedLine(string text) => Text.Append(text).Append('\n');

        public string Output() => Text.ToString();

        public void OpenScope() => Text.Append("{\n");

        public void CloseScope() => Text.Append("}\n");

        public void AddImportNamespace(string ns) { }

        public void AddImportNamespaces(IEnumerable<string> namespaces) { }

        public void GenerateUsingStatements() { }
    }
}
